import type { Workshop } from '../types/workshop';
import { mockStudios } from './mockStudios';

type WorkshopSeed = Omit<
  Workshop,
  'studioId' | 'sessions' | 'nextStartsAt' | 'rating' | 'reviewCount'
> & {
  dayOffset: number;
  startHour: number;
  seats: number;
  rating: number;
  reviewCount: number;
};

function makeWorkshop(seed: WorkshopSeed): Workshop {
  const { dayOffset, startHour, seats, ...workshop } = seed;
  const studio = mockStudios.find((item) => item.name === workshop.studioName);
  if (!studio) {
    throw new Error(`Missing mock studio for workshop ${workshop.id}.`);
  }
  const start = new Date();
  start.setDate(start.getDate() + dayOffset);
  start.setHours(startHour, 0, 0, 0);
  const end = new Date(start.getTime() + workshop.durationMinutes * 60_000);

  return {
    ...workshop,
    studioId: studio.id,
    province: studio.province,
    provinceId: studio.provinceId,
    areaId: studio.areaId,
    studioDescription: studio.description,
    isSimulated: true,
    nextStartsAt: start.toISOString(),
    sessions: [
      {
        id: `${workshop.id}-session`,
        startsAt: start.toISOString(),
        endsAt: end.toISOString(),
        price: workshop.basePrice,
        availableSeats: seats,
      },
    ],
  };
}

